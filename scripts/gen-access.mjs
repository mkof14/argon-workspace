// Generates supabase/access.sql from src/config/workspace.config.mjs
import { writeFileSync } from "node:fs";
import { allSections } from "../src/config/workspace.config.mjs";
const rows = [];
for (const s of allSections()) {
  const roles = new Map();
  for (const r of s.read) roles.set(r, false);
  for (const r of s.write) roles.set(r, true);
  for (const [r, w] of roles) rows.push(`('${s.id}','${r}',${w},false)`);
  for (const r of s.external) rows.push(`('${s.id}','${r}',false,true)`);
}
const sql = `-- Generated by scripts/gen-access.mjs — do not edit by hand.\ndelete from public.section_access;\ninsert into public.section_access (section, role, can_write, external) values\n${rows.join(",\n")};\n`;
writeFileSync(new URL("../supabase/access.sql", import.meta.url), sql);
console.log(`access.sql: ${rows.length} rules for ${allSections().length} sections`);
