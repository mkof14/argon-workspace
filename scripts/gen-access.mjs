// Generates supabase/access.sql from src/config/workspace.config.mjs
import { writeFileSync } from "node:fs";
import { allSections, defaultRules } from "../src/config/workspace.config.mjs";
const rows = defaultRules().map((r) => `('${r.section}','${r.role}',${r.can_write},${r.external})`);
const sql = `-- Generated by scripts/gen-access.mjs — do not edit by hand.\n-- Resets access to the defaults from workspace.config.mjs (custom changes made in Users & roles are overwritten).\ndelete from public.section_access;\ninsert into public.section_access (section, role, can_write, external) values\n${rows.join(",\n")};\n`;
writeFileSync(new URL("../supabase/access.sql", import.meta.url), sql);
console.log(`access.sql: ${rows.length} rules for ${allSections().length} sections`);
